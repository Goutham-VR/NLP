# What is NLP?

# NLP = Natural Language Processing.

# It is the field of AI that allows computers to work with human language.

# Examples:

# Chatbots
# Translation
# Sentiment analysis
# Spam detection
# Text classification
# Search
# Summarization
# Question answering
# LLMs like GPT

# The fundamental problem is:

# Computers work with numbers, but humans communicate using language.

# For example:

# I love Python

# A neural network cannot directly process those characters as meaningful language.

# We need something like:

# Text
#  ↓
# Tokens
#  ↓
# Numbers
#  ↓
# Vectors
#  ↓
# Neural Network

# That pipeline is the foundation of modern NLP.