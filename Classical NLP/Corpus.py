# What is a corpus?

# A corpus is a collection of text used for NLP.

# For example, suppose we have:

# I love Python.
# Python is powerful.
# I love machine learning.
# Machine learning is interesting.

# This entire collection is our corpus.

# Think:

# corpus
#  ├── sentence 1
#  ├── sentence 2
#  ├── sentence 3
#  └── sentence 4